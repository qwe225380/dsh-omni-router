/**
 * One-time smoke bootstrap (portable — no hardcoded absolute paths):
 *   1. (re)create the fixture-pagination git repo with the bug commit
 *   2. rewrite smoke.json with the real commit sha, fixture repo path and
 *      arm agent commands that work on THIS machine (8.3 short paths or a
 *      no-space temp copy of the wrappers)
 *   3. generate omni.patch.yml (official loader patch: omni-router row into
 *      the headless host composition + agentPresets.defaultId)
 *   4. write omni-package-path.txt (consumed by bootstrap-omni.cmd)
 *   5. create the isolated DSH_HOME dirs for raw/omni arms
 *
 * Run once per machine, before preflight / run.
 */

import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { execFileSync, spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))            // .../smoke
const benchmarkRoot = path.dirname(here)                              // .../omnibench-v2
const omniPkg = path.resolve(benchmarkRoot, '..', '..')               // omni-router repo root
const fixture = path.join(here, 'fixture-pagination')
const smokeJson = path.join(here, 'smoke.json')

function git(args, cwd) {
  return execFileSync('git', args, { cwd, encoding: 'utf8' }).trim()
}

function shortPath(p) {
  const res = spawnSync('powershell', [
    '-NoProfile', '-Command',
    `(New-Object -ComObject Scripting.FileSystemObject).GetFile('${p.replace(/'/g, "''")}').ShortPath`,
  ], { encoding: 'utf8' })
  const out = (res.stdout || '').trim()
  if (out && out !== p && !out.includes(' ')) return out
  return null
}

function deployWrapper(srcName) {
  const src = path.join(here, srcName)
  const short = shortPath(src)
  if (short) return short
  // No 8.3 names on this volume: copy into a no-space temp dir.
  const dir = path.join(os.tmpdir(), 'omni-smoke-bin')
  fs.mkdirSync(dir, { recursive: true })
  const dst = path.join(dir, srcName)
  fs.copyFileSync(src, dst)
  return shortPath(dst) || dst
}

// 1. fixture git (idempotent)
if (!fs.existsSync(path.join(fixture, '.git'))) {
  git(['init', '-b', 'main'], fixture)
}
const dirty = git(['status', '--porcelain'], fixture).trim() !== ''
let sha = null
try {
  sha = git(['rev-parse', 'HEAD'], fixture)
} catch { /* no commits yet */ }
if (!sha || dirty) {
  git(['add', '-A'], fixture)
  git(['-c', 'user.name=smoke', '-c', 'user.email=smoke@local', 'commit', '-m', 'bug: pagination last page off-by-one'], fixture)
  sha = git(['rev-parse', 'HEAD'], fixture)
}

// 2. rewrite smoke.json with machine-local values
const manifest = JSON.parse(fs.readFileSync(smokeJson, 'utf8'))
manifest[0].repo = fixture.replace(/\\/g, '/')
manifest[0].commit = sha
manifest[0].rawAgentCommand = `call "${deployWrapper('run-raw.cmd')}"`
manifest[0].omniAgentCommand = `call "${deployWrapper('run-omni.cmd')}"`
fs.writeFileSync(smokeJson, JSON.stringify(manifest, null, 2) + '\n')

// 3. omni patch: join the Omni Router plugin row into the headless HOST
//    plane via the official loader patch "insert list" (the shipped headless
//    bundle composes no preset roster). Best-effort defaultId override is
//    included for rosterful hosts; preflight proves the result and fails
//    closed if the overlay did not take effect.
const omniRouterSrc = path.join(omniPkg, 'src', 'omni-router.mjs').replace(/\\/g, '/')
const patchYaml = [
  '# Generated by smoke bootstrap (do not edit manually).',
  '# Omni arm overlay: mounts the Omni Router row into the headless host plane.',
  '- insert:',
  '    - id: omni-router',
  `      name: ${JSON.stringify(omniRouterSrc)}`,
  '      config:',
  '        requireConfirmation: true',
  '',
  '# Best effort: default preset id for rosterful hosts (unmatched targets are',
  '# reported on stderr and do not block the dump).',
  '- id: agent-presets',
  '  config:',
  '    defaultId: omni-router',
  '',
].join('\n')
fs.writeFileSync(path.join(here, 'omni.patch.yml'), patchYaml)

// 4. package path for bootstrap-omni.cmd
fs.writeFileSync(path.join(here, 'omni-package-path.txt'), omniPkg + '\n')

// 5. isolated DSH_HOMEs
for (const arm of ['raw', 'omni']) {
  fs.mkdirSync(path.join(here, 'homes', arm), { recursive: true })
}

console.log(`fixture ready @ ${sha}`)
console.log(`smoke.json updated (repo=${manifest[0].repo})`)
console.log(`raw  agent command: ${manifest[0].rawAgentCommand}`)
console.log(`omni agent command: ${manifest[0].omniAgentCommand}`)
console.log('omni.patch.yml + omni-package-path.txt written')
console.log('Next: bootstrap-omni.cmd, then preflight, then run.')